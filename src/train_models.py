RANDOM_STATE = 42


def _slug(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", value).strip("_")[:120]


def available_model_factories() -> tuple[dict, str | None]:
    factories = {
        "random_forest": lambda: RandomForestRegressor(
            n_estimators=200,
            min_samples_leaf=1,
            random_state=RANDOM_STATE,
            n_jobs=-1,
        ),
        "gradient_boosting": lambda: GradientBoostingRegressor(
            n_estimators=150,
            learning_rate=0.04,
            max_depth=2,
            random_state=RANDOM_STATE,
            loss="squared_error",
        ),
    }
    try:
        from xgboost import XGBRegressor

        factories["xgboost"] = lambda: XGBRegressor(
            n_estimators=200,
            max_depth=2,
            learning_rate=0.04,
            subsample=0.9,
            colsample_bytree=0.9,
            objective="reg:squarederror",
            random_state=RANDOM_STATE,
            n_jobs=1,
        )
        return factories, None
    except ImportError as exc:
        return factories, f"xgboost unavailable: {exc}"


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields = list(rows[0].keys())
    with path.open("w", newline="", encoding="utf-8") as file_obj:
        writer = csv.DictWriter(file_obj, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def _metric_text(value) -> str:
    return "NA" if value is None or value == "" else f"{float(value):.4f}"


def _build_training_report(
    prepared: dict,
    splits: dict,
    metric_rows: list[dict],
    lstm_rows: list[dict],
    forecast_rows: list[dict],
    aggregate_rows: list[dict],
    xgb_note: str | None,
) -> str:
    """Create a human-readable, evidence-based Phase 3 report."""

    lines = [
        "AgriPrice-NG Phase 3 training report",
        "====================================",
        "",
        "This report was generated by python train.py from the unchanged files in data/raw/.",
        "No missing target prices were interpolated or forward-filled.",
        "",
        "1. Data preparation and usable sample counts",
        "----------------------------------------------",
        "The five approved market-level series were kept separate by commodity, market, unit, and price type.",
        "Each series was reindexed to calendar months before features were created. Required features were",
        "price_lag_1, price_lag_2, price_lag_3, rolling_mean_3, rolling_std_3, month_sin, month_cos,",
        "and trend_index. A training row was retained only when all calendar-based historical values existed.",
        "",
        f"Approved source observations: {len(prepared['approved_rows']):,}",
        f"Calendar rows after reindexing: {len(prepared['monthly_rows']):,}",
        f"Usable feature rows: {len(prepared['feature_rows']):,}",
        "",
    ]
    for diagnostic in sorted(prepared["diagnostics"], key=lambda row: row["series_id"]):
        series_id = diagnostic["series_id"]
        split = splits[series_id]
        lines.append(
            f"{series_id}: observed={diagnostic['observed_rows']}, "
            f"calendar={diagnostic['calendar_rows']}, usable={diagnostic['usable_feature_rows']}, "
            f"excluded_missing_history={diagnostic['excluded_missing_history_rows']}, "
            f"split(train/validation/test)={len(split['train'])}/{len(split['validation'])}/{len(split['test'])}"
        )

    lines.extend(
        [
            "",
            "2. Chronological evaluation and model status",
            "----------------------------------------------",
            "The split is 70% train, 15% validation, and 15% test within each series; observations were not shuffled.",
            "All models listed as trained for a series use the same test months for that series. The naive baseline",
            "uses the price from the immediately preceding calendar month (price_lag_1). MAPE excludes zero actuals.",
            "",
            "Test metrics (RMSE | MAE | MAPE percent | R2):",
        ]
    )
    model_order = ["naive_last_calendar_month", "random_forest", "gradient_boosting", "stacking", "xgboost"]
    for series_id in sorted({row["series_id"] for row in metric_rows}):
        lines.append(f"{series_id}")
        series_test = {
            row["model"]: row
            for row in metric_rows
            if row["series_id"] == series_id and row["split"] == "test"
        }
        for model_name in model_order:
            row = series_test.get(model_name)
            if row is None:
                continue
            status = row["status"]
            if status == "trained":
                values = " | ".join(
                    _metric_text(row[field]) for field in ("rmse", "mae", "mape", "r2")
                )
                lines.append(f"  {model_name}: {values} (n_test={row['n_test']})")
            else:
                lines.append(f"  {model_name}: {status}; {row['notes']}")

    lines.extend(
        [
            "",
            "3. XGBoost and LSTM limitations",
            "--------------------------------",
            f"XGBoost: {xgb_note or 'dependency available and trained'}.",
            "No XGBoost metric is reported when the dependency is unavailable; this is not treated as a failed numerical result.",
            "",
            "LSTM exploratory experiment (12-month complete calendar sequence window):",
        ]
    )
    for row in sorted(lstm_rows, key=lambda item: item["series_id"]):
        lines.append(
            f"  {row['series_id']}: sequences={row['sequence_count']}, "
            f"train/validation/test={row['train_sequences']}/{row['validation_sequences']}/{row['test_sequences']}, "
            f"status={row['status']}; {row['notes']}"
        )
    lines.extend(
        [
            "The LSTM path uses a small Keras architecture with early stopping when enough sequences exist.",
            "The primary series do not have enough complete sequences for a defensible exploratory result, so no LSTM result is presented as reliable.",
            "",
            "4. Recursive forecast output",
            "----------------------------",
            "Forecasts are generated recursively: each predicted calendar month is added to the history used for later horizons.",
            "A missing historical calendar lag stops recursion rather than substituting an older observation or an imputed value.",
        ]
    )
    status_counts: dict[str, int] = {}
    for row in forecast_rows:
        status_counts[row["status"]] = status_counts.get(row["status"], 0) + 1
    lines.append(
        "Forecast rows by status: "
        + ", ".join(f"{status}={count}" for status, count in sorted(status_counts.items()))
    )
    lines.append(
        "The forecast CSV contains one row for each model/series/horizon (1, 3, and 6 months); unavailable rows identify the requested future month."
    )
    lines.extend(
        [
            "",
            "5. Supplementary commodity-month aggregate audit",
            "------------------------------------------------",
            f"Aggregate rows written: {len(aggregate_rows):,}.",
            "Aggregates are separate by commodity, price type, exact unit, and month; no retail/wholesale or unit conversion was performed.",
            "Each aggregate row records mean_price, median_price, n_markets, n_records, and observed currency values.",
            "Aggregates are supplementary only and do not replace the five approved market-level training series.",
            "",
            "Interpretation caution",
            "---------------------",
            "The approved series are irregular and fail the strict continuity criterion documented in Phase 2.",
            "Small chronological test sets make metrics volatile; negative R2 values mean the model is worse than a test-period mean for that series, not that prices are negative.",
            "Forecasts that are marked unavailable should not be interpreted as zero prices or as evidence that a series had no market activity.",
        ]
    )
    return "\n".join(lines) + "\n"


def _save_model(model, series_id: str, model_name: str, metadata: dict) -> Path:
    path = MODELS_DIR / _slug(series_id)
    path.mkdir(parents=True, exist_ok=True)
    output = path / f"{model_name}.joblib"
    joblib.dump({"model": model, "metadata": metadata}, output)
    return output


def _oof_predictions(factory, x: np.ndarray, y: np.ndarray) -> np.ndarray:
    n_splits = 3 if len(y) >= 12 else 2
    if len(y) <= n_splits + 1:
        return np.full(len(y), np.nan)
    splitter = TimeSeriesSplit(n_splits=n_splits)
    output = np.full(len(y), np.nan)
    for train_index, validation_index in splitter.split(x):
        if len(train_index) < 3:
            continue
        model = factory()
        model.fit(x[train_index], y[train_index])
        output[validation_index] = model.predict(x[validation_index])
    return output


def _fit_stacking(
    series_id: str,
    train_rows: list[dict],
    validation_rows: list[dict],
    test_rows: list[dict],
    factories: dict,
) -> tuple[dict | None, list[dict], dict | None, str]:
    base_names = [name for name in ("random_forest", "gradient_boosting", "xgboost") if name in factories]
    if len(base_names) < 2:
        return None, [], None, "fewer than two base models available"
    x_train, y_train = rows_to_arrays(train_rows)
    x_test, y_test = rows_to_arrays(test_rows)
    oof_by_model = {name: _oof_predictions(factories[name], x_train, y_train) for name in base_names}
    valid_mask = np.ones(len(y_train), dtype=bool)
    for values in oof_by_model.values():
        valid_mask &= np.isfinite(values)
    if int(valid_mask.sum()) < 4:
        return None, [], None, "insufficient chronological out-of-fold predictions"

    oof_matrix = np.column_stack([oof_by_model[name][valid_mask] for name in base_names])
    meta = Ridge(alpha=1.0)
    meta.fit(oof_matrix, y_train[valid_mask])
    base_models = {}
    test_matrix = []
    validation_matrix = []
    x_validation = rows_to_arrays(validation_rows)[0] if validation_rows else None
    for name in base_names:
        base = factories[name]()
        base.fit(x_train, y_train)
        base_models[name] = base
        test_matrix.append(base.predict(x_test))
        if x_validation is not None:
            validation_matrix.append(base.predict(x_validation))
    test_prediction = meta.predict(np.column_stack(test_matrix))
    validation_prediction = (
        meta.predict(np.column_stack(validation_matrix)) if validation_matrix else None
    )
    bundle = {"base_models": base_models, "meta_model": meta, "feature_columns": FEATURE_COLUMNS}
    validation_bundle = {
        "test_prediction": test_prediction,
        "validation_prediction": validation_prediction,
        "base_names": base_names,
    }
    return bundle, base_names, validation_bundle, "trained with chronological OOF base predictions"


def train_all() -> dict:
    prepared = prepare_approved_data()
    splits = split_feature_rows(prepared["feature_rows"])
    factories, xgb_note = available_model_factories()
    metric_rows: list[dict] = []
    prediction_records: list[dict] = []
    fitted_models: dict[str, dict[str, object]] = {}

    for series_id, split in sorted(splits.items()):
        train_rows = split["train"]
        validation_rows = split["validation"]
        test_rows = split["test"]
        train_count = len(train_rows)
        validation_count = len(validation_rows)
        test_count = len(test_rows)
        fitted_models[series_id] = {}

        if train_count < 8 or test_count < 2:
            note = "insufficient chronological rows for a train/test comparison"
            for model_name in ["naive_last_calendar_month", "random_forest", "xgboost", "gradient_boosting", "stacking"]:
                metric_rows.append(
                    create_metric_row(
                        series_id=series_id,
                        model=model_name,
                        split="test",
                        train_count=train_count,
                        validation_count=validation_count,
                        test_count=test_count,
                        metrics={},
                        status="insufficient_data",
                        notes=note,
                    )
                )
            continue

        x_train, y_train = rows_to_arrays(train_rows)
        x_validation, y_validation = rows_to_arrays(validation_rows) if validation_rows else (None, None)
        x_test, y_test = rows_to_arrays(test_rows)
        months_test = [row["month"] for row in test_rows]
        naive_prediction = np.asarray([float(row["price_lag_1"]) for row in test_rows])
        naive_metrics = regression_metrics(y_test, naive_prediction)
        metric_rows.append(
            create_metric_row(
                series_id=series_id,
                model="naive_last_calendar_month",
                split="test",
                train_count=train_count,
                validation_count=validation_count,
                test_count=test_count,
                metrics=naive_metrics,
                notes="Uses price from the immediately preceding calendar month only.",
            )
        )
        prediction_records.append(
            {
                "series_id": series_id,
                "model": "naive_last_calendar_month",
                "months": months_test,
                "actual": y_test.tolist(),
                "predicted": naive_prediction.tolist(),
                "baseline": None,
            }
        )

        for model_name, factory in factories.items():
            model = factory()
            model.fit(x_train, y_train)
            prediction = model.predict(x_test)
            metrics = regression_metrics(y_test, prediction)
            notes = ""
            if model_name == "xgboost" and xgb_note:
                notes = xgb_note
            model_path = _save_model(
                model,
                series_id,
                model_name,
                {"series_id": series_id, "feature_columns": FEATURE_COLUMNS},
            )
            fitted_models[series_id][model_name] = model
            metric_rows.append(
                create_metric_row(
                    series_id=series_id,
                    model=model_name,
                    split="test",
                    train_count=train_count,
                    validation_count=validation_count,
                    test_count=test_count,
                    metrics=metrics,
                    notes=f"Saved to {model_path}; {notes}".strip(),
                )
            )
            prediction_records.append(
                {
                    "series_id": series_id,
                    "model": model_name,
                    "months": months_test,
                    "actual": y_test.tolist(),
                    "predicted": prediction.tolist(),
                    "baseline": naive_prediction.tolist(),
                }
            )
            if validation_rows:
                validation_prediction = model.predict(x_validation)
                metric_rows.append(
                    create_metric_row(
                        series_id=series_id,
                        model=model_name,
                        split="validation",
                        train_count=train_count,
                        validation_count=validation_count,
                        test_count=test_count,
                        metrics=regression_metrics(y_validation, validation_prediction),
                        notes="Validation period kept chronological and separate from test.",
                    )
                )

        if xgb_note:
            metric_rows.append(
                create_metric_row(
                    series_id=series_id,
                    model="xgboost",
                    split="test",
                    train_count=train_count,
                    validation_count=validation_count,
                    test_count=test_count,
                    metrics={},
                    status="not_trained_missing_dependency",
                    notes=xgb_note,
                )
            )

        stack_bundle, base_names, stack_predictions, stack_note = _fit_stacking(
            series_id, train_rows, validation_rows, test_rows, factories
        )
        if stack_bundle is None or stack_predictions is None:
            metric_rows.append(
                create_metric_row(
                    series_id=series_id,
                    model="stacking",
                    split="test",
                    train_count=train_count,
                    validation_count=validation_count,
                    test_count=test_count,
                    metrics={},
                    status="not_trained",
                    notes=stack_note,
                )
            )
        else:
            stack_path = _save_model(
                stack_bundle,
                series_id,
                "stacking",
                {
                    "series_id": series_id,
                    "feature_columns": FEATURE_COLUMNS,
                    "base_models": base_names,
                    "meta_training": "chronological out-of-fold predictions",
                },
            )
            stack_prediction = stack_predictions["test_prediction"]
            fitted_models[series_id]["stacking"] = stack_bundle
            metric_rows.append(
                create_metric_row(
                    series_id=series_id,
                    model="stacking",
                    split="test",
                    train_count=train_count,
                    validation_count=validation_count,
                    test_count=test_count,
                    metrics=regression_metrics(y_test, stack_prediction),
                    notes=f"Saved to {stack_path}; {stack_note}; bases={','.join(base_names)}",
                )
            )
            prediction_records.append(
                {
                    "series_id": series_id,
                    "model": "stacking",
                    "months": months_test,
                    "actual": y_test.tolist(),
                    "predicted": stack_prediction.tolist(),
                    "baseline": naive_prediction.tolist(),
                }
            )

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump(
        {"feature_columns": FEATURE_COLUMNS, "target_column": TARGET_COLUMN},
        MODELS_DIR / "preprocessing_metadata.joblib",
    )
    _write_csv(REPORTS_DIR / "model_comparison.csv", metric_rows)
    _write_csv(REPORTS_DIR / "individual_series_metrics.csv", metric_rows)

    for record in prediction_records:
        write_actual_predicted_svg(
            PLOTS_DIR
            / f"{_slug(record['series_id'])}__{record['model']}.svg",
            f"{record['series_id']} — {record['model']}",
            record["months"],
            record["actual"],
            record["predicted"],
            record["baseline"],
        )

    forecast_rows: list[dict] = []
    monthly_by_series: dict[str, list[dict]] = {}
    for row in prepared["monthly_rows"]:
        sid = " | ".join(
            [row["commodity"], row["market"], row["unit"], row["price_type"]]
        )
        monthly_by_series.setdefault(sid, []).append(row)
    for series_id, model_map in fitted_models.items():
        for model_name, model in model_map.items():
            if model_name == "stacking":
                # The forecasting helper expects a sklearn-like predict method.
                class StackingPredictor:
                    def __init__(self, bundle):
                        self.bundle = bundle

                    def predict(self, values):
                        base_values = np.column_stack(
                            [model.predict(values) for model in self.bundle["base_models"].values()]
                        )
                        return self.bundle["meta_model"].predict(base_values)

                forecast_model = StackingPredictor(model)
            else:
                forecast_model = model
            forecast_rows.extend(
                recursive_forecast(
                    forecast_model,
                    monthly_by_series[series_id],
                    series_id,
                    model_name,
                )
            )
    write_forecasts(FORECASTS_DIR / "recursive_forecasts.csv", forecast_rows)

    # Supplementary audit only: this does not replace the five approved
    # market-level series and keeps commodity, price type, and exact unit
    # separate. Each row records how many markets contributed.
    aggregate_rows = build_commodity_monthly_aggregates(load_all_rows())
    write_aggregates(
        ROOT / "data" / "processed" / "commodity_monthly_aggregates.csv",
        aggregate_rows,
    )
    lstm_rows = run_lstm_experiment(prepared)

    config = {
        "approved_series": list(prepared["source_counts"].keys()),
        "target": TARGET_COLUMN,
        "feature_columns": FEATURE_COLUMNS,
        "chronological_split": {"train": 0.70, "validation": 0.15, "test": 0.15},
        "random_state": RANDOM_STATE,
        "xgboost_dependency_note": xgb_note,
        "models_trained": sorted({row["model"] for row in metric_rows if row["status"] == "trained"}),
        "lstm": "exploratory stage reported separately; primary series lack reliable 12-month runs",
        "aggregate_rows": len(aggregate_rows),
        "lstm_statuses": sorted({row["status"] for row in lstm_rows}),
    }
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "experiment_config.json").write_text(
        json.dumps(config, indent=2, default=str), encoding="utf-8"
    )
    report_text = _build_training_report(
        prepared,
        splits,
        metric_rows,
        lstm_rows,
        forecast_rows,
        aggregate_rows,
        xgb_note,
    )
    (REPORTS_DIR / "model_performance_report.txt").write_text(
        report_text,
        encoding="utf-8",
    )
    (REPORTS_DIR / "training_summary.txt").write_text(
        report_text,
        encoding="utf-8",
    )
    return {"prepared": prepared, "metrics": metric_rows, "forecasts": forecast_rows}
